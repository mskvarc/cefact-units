//! Rendering of the identified code records as the Rust source `cefact-units/src/generated.rs`.
//!
//! The output holds only what follows from the code list: the two enums, their per-code `match` tables, `ALL`,
//! `LATEST_REVISION` and `SOURCES`. Every type and impl that does not vary with the codes is written by hand in
//! `cefact-units/src/lib.rs`, which includes this file. Every list is written in identity order, so the derived `Ord`
//! of both enums orders by identity.

use crate::catalogue::UnitRecord;
use crate::generation_error::GenerationError;
use crate::identity_registry::IdentifiedUnit;
use crate::source_file::SourceFile;
use crate::status::Status;
use std::fmt::Write;

/// Renders the generated file for `units`, in identity order, read from `source`.
pub fn render(
    units: &[IdentifiedUnit<'_>],
    source: &SourceFile,
) -> Result<String, GenerationError> {
    let records: Vec<&UnitRecord> = units.iter().map(|identified| identified.unit).collect();
    let mut out = String::new();
    writeln!(
        out,
        "// @generated by cefact-units-generator. Do not edit: run `cargo run -p cefact-units-generator -- generate`."
    )?;
    render_unit_code_enum(&mut out, units)?;
    render_unit_code_impl(&mut out, &records)?;
    render_unit_of_measure(&mut out, &records)?;
    render_sources(&mut out, source)?;
    Ok(out)
}

/// The `UnitCode` enum, each variant's discriminant its identity.
fn render_unit_code_enum(
    out: &mut String,
    units: &[IdentifiedUnit<'_>],
) -> Result<(), GenerationError> {
    writeln!(out)?;
    writeln!(
        out,
        "/// Canonical UN/CEFACT common code (for example: `\"MTR\"`, `\"KGM\"`)."
    )?;
    writeln!(out, "///")?;
    writeln!(
        out,
        "/// Each discriminant is the code's identity: assigned once, never reused, never above `32767`."
    )?;
    writeln!(
        out,
        "#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]"
    )?;
    writeln!(out, "#[non_exhaustive]")?;
    writeln!(out, "#[repr(u16)]")?;
    writeln!(out, "pub enum UnitCode {{")?;
    for identified in units {
        writeln!(out, "    /// Code `{}`.", identified.unit.code)?;
        writeln!(
            out,
            "    {} = {},",
            identified.unit.code_variant,
            identified.identity.get()
        )?;
    }
    writeln!(out, "}}")?;
    Ok(())
}

/// `UnitCode::as_str` and `UnitCode::from_code`.
fn render_unit_code_impl(out: &mut String, units: &[&UnitRecord]) -> Result<(), GenerationError> {
    writeln!(out)?;
    writeln!(out, "impl UnitCode {{")?;
    writeln!(out, "    /// Returns this code as a static string.")?;
    writeln!(out, "    #[inline]")?;
    writeln!(out, "    #[must_use]")?;
    writeln!(out, "    pub const fn as_str(self) -> &'static str {{")?;
    writeln!(out, "        match self {{")?;
    for unit in units {
        writeln!(
            out,
            "            Self::{} => {:?},",
            unit.code_variant, unit.code
        )?;
    }
    writeln!(out, "        }}")?;
    writeln!(out, "    }}")?;
    writeln!(out)?;
    writeln!(
        out,
        "    /// Look up a code by its string representation (case-sensitive)."
    )?;
    writeln!(out, "    #[inline]")?;
    writeln!(out, "    #[must_use]")?;
    writeln!(out, "    pub fn from_code(code: &str) -> Option<Self> {{")?;
    writeln!(out, "        match code {{")?;
    for unit in units {
        writeln!(
            out,
            "            {:?} => Some(Self::{}),",
            unit.code, unit.code_variant
        )?;
    }
    writeln!(out, "            _ => None,")?;
    writeln!(out, "        }}")?;
    writeln!(out, "    }}")?;
    writeln!(out, "}}")?;
    Ok(())
}

/// The `UnitOfMeasure` enum with `info`, `unit_code`, `from_unit_code` and `ALL`.
fn render_unit_of_measure(out: &mut String, units: &[&UnitRecord]) -> Result<(), GenerationError> {
    writeln!(out)?;
    writeln!(
        out,
        "/// Every UN/CEFACT unit of measure Recommendation No. 20 lists, whatever its status."
    )?;
    writeln!(out, "///")?;
    writeln!(
        out,
        "/// Use [`UnitOfMeasure::from_code`] to look up by common code,"
    )?;
    writeln!(out, "/// or iterate [`UnitOfMeasure::ALL`].")?;
    writeln!(
        out,
        "#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]"
    )?;
    writeln!(out, "#[non_exhaustive]")?;
    writeln!(out, "pub enum UnitOfMeasure {{")?;
    for unit in units {
        writeln!(out, "    /// Unit `{}`.", unit.code)?;
        writeln!(out, "    {},", unit.unit_variant)?;
    }
    writeln!(out, "}}")?;
    writeln!(out)?;
    writeln!(out, "impl UnitOfMeasure {{")?;
    writeln!(out, "    /// Returns all static metadata for this unit.")?;
    writeln!(out, "    #[inline]")?;
    writeln!(out, "    #[must_use]")?;
    writeln!(out, "    pub const fn info(self) -> UnitInfo {{")?;
    writeln!(out, "        match self {{")?;
    for unit in units {
        writeln!(
            out,
            "            Self::{} => UnitInfo {{",
            unit.unit_variant
        )?;
        writeln!(out, "                code: {:?},", unit.code)?;
        writeln!(out, "                name: {:?},", unit.name)?;
        writeln!(
            out,
            "                symbol: {},",
            optional_literal(unit.symbol.as_deref())
        )?;
        writeln!(
            out,
            "                quantity: {},",
            optional_literal(unit.quantity.as_deref())
        )?;
        writeln!(
            out,
            "                sector: {},",
            optional_literal(unit.sector.as_deref())
        )?;
        writeln!(
            out,
            "                conversion_factor: {},",
            optional_literal(unit.conversion_factor.as_deref())
        )?;
        writeln!(
            out,
            "                level_category: {},",
            optional_literal(unit.level_category.as_deref())
        )?;
        writeln!(
            out,
            "                description: {},",
            optional_literal(unit.description.as_deref())
        )?;
        writeln!(out, "                status: {},", status_path(unit.status))?;
        writeln!(out, "            }},")?;
    }
    writeln!(out, "        }}")?;
    writeln!(out, "    }}")?;
    writeln!(out)?;
    writeln!(out, "    /// Returns this unit's strongly-typed code.")?;
    writeln!(out, "    #[inline]")?;
    writeln!(out, "    #[must_use]")?;
    writeln!(out, "    pub const fn unit_code(self) -> UnitCode {{")?;
    writeln!(out, "        match self {{")?;
    for unit in units {
        writeln!(
            out,
            "            Self::{} => UnitCode::{},",
            unit.unit_variant, unit.code_variant
        )?;
    }
    writeln!(out, "        }}")?;
    writeln!(out, "    }}")?;
    writeln!(out)?;
    writeln!(out, "    /// Converts a code into its associated unit.")?;
    writeln!(out, "    #[inline]")?;
    writeln!(out, "    #[must_use]")?;
    writeln!(
        out,
        "    pub const fn from_unit_code(code: UnitCode) -> Self {{"
    )?;
    writeln!(out, "        match code {{")?;
    for unit in units {
        writeln!(
            out,
            "            UnitCode::{} => Self::{},",
            unit.code_variant, unit.unit_variant
        )?;
    }
    writeln!(out, "        }}")?;
    writeln!(out, "    }}")?;
    writeln!(out)?;
    writeln!(
        out,
        "    /// Every unit in identity order: `ALL[i]` is the unit whose code has identity `i + 1`."
    )?;
    writeln!(
        out,
        "    pub const ALL: &'static [Self; {}] = &[",
        units.len()
    )?;
    for unit in units {
        writeln!(out, "        Self::{},", unit.unit_variant)?;
    }
    writeln!(out, "    ];")?;
    writeln!(out, "}}")?;
    Ok(())
}

/// `LATEST_REVISION` and `SOURCES`.
fn render_sources(out: &mut String, source: &SourceFile) -> Result<(), GenerationError> {
    let digest: Vec<String> = source
        .sha256
        .iter()
        .map(|byte| format!("0x{byte:02x}"))
        .collect();
    writeln!(out)?;
    writeln!(
        out,
        "/// Latest revision of Recommendation No. 20 the code list is generated from."
    )?;
    writeln!(
        out,
        "pub const LATEST_REVISION: Revision = Revision({});",
        source.revision
    )?;
    writeln!(out)?;
    writeln!(
        out,
        "/// Every source workbook the code list is generated from."
    )?;
    writeln!(out, "pub const SOURCES: &[SourceFile] = &[SourceFile {{")?;
    writeln!(out, "    revision: Revision({}),", source.revision)?;
    writeln!(out, "    sha256: [{}],", digest.join(", "))?;
    writeln!(out, "}}];")?;
    Ok(())
}

/// `Some("…")` or `None` as Rust source. The `Debug` rendering of a `str` is a valid Rust string literal.
fn optional_literal(value: Option<&str>) -> String {
    value.map_or_else(|| "None".to_owned(), |text| format!("Some({text:?})"))
}

/// Path of the library `Status` variant for `status`.
const fn status_path(status: Status) -> &'static str {
    match status {
        Status::Current => "Status::Current",
        Status::Deprecated => "Status::Deprecated",
        Status::Deleted => "Status::Deleted",
    }
}
