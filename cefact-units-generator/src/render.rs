//! Rendering of the identified code records as the Rust source `cefact-units/src/generated.rs`.
//!
//! The output holds only what follows from the code list: the `UnitCode` enum, `ALL`, the record table, the
//! text-ordered lookup table, `LATEST_REVISION` and `SOURCES`. Every type and impl that does not vary with the codes is
//! written by hand in `cefact-units/src/lib.rs`, which includes this file. The per-code data is constant tables rather
//! than `match` arms, so no generated function grows with the code list.

use crate::catalogue::UnitRecord;
use crate::generation_error::GenerationError;
use crate::identity_registry::IdentifiedUnit;
use crate::source_file::SourceFile;
use crate::status::Status;
use std::fmt::Write;

/// Renders the generated file for `units`, in identity order, read from `source`.
pub fn render(
    units: &[IdentifiedUnit<'_>],
    source: &SourceFile,
) -> Result<String, GenerationError> {
    let records: Vec<&UnitRecord> = units.iter().map(|identified| identified.unit).collect();
    let mut out = String::new();
    writeln!(
        out,
        "// @generated by cefact-units-generator. Do not edit: run `cargo run -p cefact-units-generator -- generate`."
    )?;
    render_unit_code_enum(&mut out, units)?;
    render_all(&mut out, &records)?;
    render_records(&mut out, &records)?;
    render_codes_by_text(&mut out, &records)?;
    render_sources(&mut out, source)?;
    Ok(out)
}

/// The `UnitCode` enum in identity order, each variant's discriminant its identity, so the derived `Ord` orders by
/// identity.
fn render_unit_code_enum(
    out: &mut String,
    units: &[IdentifiedUnit<'_>],
) -> Result<(), GenerationError> {
    writeln!(out)?;
    writeln!(
        out,
        "/// A UN/CEFACT common code (for example `MTR`, `KGM`), whatever its status."
    )?;
    writeln!(out, "///")?;
    writeln!(
        out,
        "/// Each discriminant is the code's identity, [`UnitCode::id`]: assigned once, never reused, never above `32767`."
    )?;
    writeln!(
        out,
        "#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]"
    )?;
    writeln!(out, "#[non_exhaustive]")?;
    writeln!(out, "#[repr(u16)]")?;
    writeln!(out, "pub enum UnitCode {{")?;
    for identified in units {
        let unit = identified.unit;
        writeln!(
            out,
            "    /// `{}`: {}.{}",
            unit.code,
            quoted_name(&unit.name),
            status_note(unit.status)
        )?;
        writeln!(
            out,
            "    {} = {},",
            unit.code_variant,
            identified.identity.get()
        )?;
    }
    writeln!(out, "}}")?;
    Ok(())
}

/// `UnitCode::ALL`, in identity order.
fn render_all(out: &mut String, units: &[&UnitRecord]) -> Result<(), GenerationError> {
    writeln!(out)?;
    writeln!(out, "impl UnitCode {{")?;
    writeln!(
        out,
        "    /// Every code in identity order: `ALL[i]` is the code with identity `i + 1`."
    )?;
    writeln!(out, "    pub const ALL: &'static [Self] = &[")?;
    for unit in units {
        writeln!(out, "        Self::{},", unit.code_variant)?;
    }
    writeln!(out, "    ];")?;
    writeln!(out, "}}")?;
    Ok(())
}

/// `RECORDS`, every code's metadata in identity order.
fn render_records(out: &mut String, units: &[&UnitRecord]) -> Result<(), GenerationError> {
    writeln!(out)?;
    writeln!(
        out,
        "/// Every code's metadata in identity order: `RECORDS[i]` belongs to the code with identity `i + 1`."
    )?;
    writeln!(out, "const RECORDS: &[UnitInfo] = &[")?;
    for unit in units {
        writeln!(out, "    UnitInfo {{")?;
        writeln!(out, "        code: {:?},", unit.code)?;
        writeln!(out, "        name: {:?},", unit.name)?;
        for (field, value) in [
            ("symbol", &unit.symbol),
            ("quantity", &unit.quantity),
            ("sector", &unit.sector),
            ("conversion_factor", &unit.conversion_factor),
            ("level_category", &unit.level_category),
            ("description", &unit.description),
        ] {
            writeln!(
                out,
                "        {field}: {},",
                optional_literal(value.as_deref())
            )?;
        }
        writeln!(out, "        status: {},", status_path(unit.status))?;
        writeln!(out, "    }},")?;
    }
    writeln!(out, "];")?;
    Ok(())
}

/// `CODES_BY_TEXT`, every code in ascending byte order of its text, so a lookup by text is a binary search.
fn render_codes_by_text(out: &mut String, units: &[&UnitRecord]) -> Result<(), GenerationError> {
    let mut ascending = units.to_vec();
    ascending.sort_by(|left, right| left.code.cmp(&right.code));
    writeln!(out)?;
    writeln!(
        out,
        "/// Every code in ascending byte order of its text, for binary search by text."
    )?;
    writeln!(out, "const CODES_BY_TEXT: &[UnitCode] = &[")?;
    for unit in ascending {
        writeln!(out, "    UnitCode::{},", unit.code_variant)?;
    }
    writeln!(out, "];")?;
    Ok(())
}

/// `LATEST_REVISION` and `SOURCES`.
fn render_sources(out: &mut String, source: &SourceFile) -> Result<(), GenerationError> {
    let digest: Vec<String> = source
        .sha256
        .iter()
        .map(|byte| format!("0x{byte:02x}"))
        .collect();
    writeln!(out)?;
    writeln!(
        out,
        "/// Latest revision of Recommendation No. 20 the code list is generated from."
    )?;
    writeln!(
        out,
        "pub const LATEST_REVISION: Revision = Revision({});",
        source.revision
    )?;
    writeln!(out)?;
    writeln!(
        out,
        "/// Every source workbook the code list is generated from."
    )?;
    writeln!(out, "pub const SOURCES: &[SourceFile] = &[SourceFile {{")?;
    writeln!(out, "    revision: Revision({}),", source.revision)?;
    writeln!(out, "    sha256: [{}],", digest.join(", "))?;
    writeln!(out, "}}];")?;
    Ok(())
}

/// `name` as a code span on one doc line. The workbook's name is quoted verbatim, unit symbols included, and a name
/// cell can span lines.
fn quoted_name(name: &str) -> String {
    let words: Vec<&str> = name.split_whitespace().collect();
    format!("`{}`", words.join(" "))
}

/// The sentence a variant doc ends with for `status`, empty for a current code.
const fn status_note(status: Status) -> &'static str {
    match status {
        Status::Current => "",
        Status::Deprecated => " Deprecated.",
        Status::Deleted => " Deleted.",
    }
}

/// `Some("…")` or `None` as Rust source. The `Debug` rendering of a `str` is a valid Rust string literal.
fn optional_literal(value: Option<&str>) -> String {
    value.map_or_else(|| "None".to_owned(), |text| format!("Some({text:?})"))
}

/// Path of the library `Status` variant for `status`.
const fn status_path(status: Status) -> &'static str {
    match status {
        Status::Current => "Status::Current",
        Status::Deprecated => "Status::Deprecated",
        Status::Deleted => "Status::Deleted",
    }
}

#[cfg(test)]
mod tests {
    use crate::catalogue::UnitRecord;
    use crate::identity_registry::IdentityRegistry;
    use crate::render::quoted_name;
    use crate::render::render_codes_by_text;
    use crate::render::render_unit_code_enum;
    use crate::status::Status;

    fn unit(code: &str, name: &str, status: Status) -> UnitRecord {
        UnitRecord {
            code: code.to_owned(),
            code_variant: code.to_owned(),
            name: name.to_owned(),
            symbol: None,
            quantity: None,
            sector: None,
            conversion_factor: None,
            level_category: None,
            description: None,
            status,
        }
    }

    #[test]
    fn a_name_spanning_lines_is_quoted_on_one_doc_line() {
        assert_eq!(
            quoted_name("A unit of pressure.\nUse kip per square inch (common code N20)."),
            "`A unit of pressure. Use kip per square inch (common code N20).`"
        );
        assert_eq!(quoted_name("quad (1015 BtuIT)"), "`quad (1015 BtuIT)`");
    }

    #[test]
    fn a_variant_is_documented_with_its_name_and_any_withdrawn_status() {
        let units = [
            unit("KGM", "kilogram", Status::Current),
            unit("A1", "15 °C calorie", Status::Deprecated),
            unit("KTM", "kilometre", Status::Deleted),
        ];
        let mut out = String::new();
        let rendered = IdentityRegistry::parse("")
            .and_then(|registry| registry.assign(&units))
            .and_then(|assignment| render_unit_code_enum(&mut out, &assignment.units));
        assert!(rendered.is_ok());
        assert!(
            out.contains("    /// `A1`: `15 °C calorie`. Deprecated.\n    A1 = 1,\n"),
            "{out}"
        );
        assert!(
            out.contains("    /// `KGM`: `kilogram`.\n    KGM = 2,\n"),
            "{out}"
        );
        assert!(
            out.contains("    /// `KTM`: `kilometre`. Deleted.\n    KTM = 3,\n"),
            "{out}"
        );
    }

    #[test]
    fn the_text_table_lists_codes_in_ascending_byte_order() {
        let units = [
            unit("KGM", "kilogram", Status::Current),
            unit(
                "A10",
                "ampere square metre per joule second",
                Status::Current,
            ),
            unit("A1", "15 °C calorie", Status::Deprecated),
            unit("10", "group", Status::Current),
        ];
        let records: Vec<&UnitRecord> = units.iter().collect();
        let mut out = String::new();
        assert!(render_codes_by_text(&mut out, &records).is_ok());
        assert!(
            out.contains(
                "    UnitCode::10,\n    UnitCode::A1,\n    UnitCode::A10,\n    UnitCode::KGM,\n];\n"
            ),
            "{out}"
        );
    }
}
